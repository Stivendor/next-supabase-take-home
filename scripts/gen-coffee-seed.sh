#!/usr/bin/env bash
# Generates supabase/seeds/coffee_health.sql from the CSV.
# `supabase db reset` loads it after the migrations (see [db.seed] in config.toml).
# Run it again if the CSV changes.
#
# ponytail: batched INSERTs of 1000 rows because the Supabase CLI seed does not
# support COPY FROM stdin. For millions of rows, load with COPY straight into Postgres.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

CSV=data/synthetic_coffee_health_10000.csv
OUT=supabase/seeds/coffee_health.sql
EXPECTED_HEADER="ID,Age,Gender,Country,Coffee_Intake,Caffeine_mg,Sleep_Hours,Sleep_Quality,BMI,Heart_Rate,Stress_Level,Physical_Activity_Hours,Health_Issues,Occupation,Smoking,Alcohol_Consumption"
COLUMNS="id, age, gender, country, coffee_intake, caffeine_mg, sleep_hours, sleep_quality, bmi, heart_rate, stress_level, physical_activity_hours, health_issues, occupation, smoking, alcohol_consumption"

# Columns are assigned by position: a reordered CSV would load values into the
# wrong column without an error (e.g. Sleep_Hours <-> BMI).
header="$(head -n1 "$CSV" | tr -d '\r')"
if [[ "$header" != "$EXPECTED_HEADER" ]]; then
  echo "error: unexpected header in $CSV" >&2
  echo "  expected: $EXPECTED_HEADER" >&2
  echo "  actual:   $header" >&2
  exit 1
fi

mkdir -p "$(dirname "$OUT")"
{
  echo "-- Generated by scripts/gen-coffee-seed.sh from $CSV. Do not edit by hand."
  tail -n +2 "$CSV" | tr -d '\r' | awk -F, -v q="'" -v cols="$COLUMNS" -v batch=1000 '
    BEGIN {
      # Text, enum and boolean (0/1) columns are quoted; the rest is numeric.
      split("3 4 8 11 13 14 15 16", idx, " ")
      for (i in idx) quoted[idx[i]] = 1
    }
    NF != 16 { printf "error: line %d has %d columns\n", NR + 1, NF > "/dev/stderr"; failed = 1; exit }
    {
      row = ""
      for (i = 1; i <= NF; i++) {
        v = $i
        if (i in quoted) {
          gsub(q, q q, v)
          v = q v q
        } else if (v !~ /^-?[0-9]+(\.[0-9]+)?$/) {
          printf "error: line %d, column %d is not numeric: %s\n", NR + 1, i, v > "/dev/stderr"
          failed = 1
          exit
        }
        row = row (i > 1 ? ", " : "") v
      }
      if ((NR - 1) % batch == 0) printf "insert into public.coffee_health (%s) values\n", cols
      else printf ",\n"
      printf "  (%s)", row
      if (NR % batch == 0) printf ";\n"
    }
    END {
      if (failed) exit 1
      if (NR % batch != 0) printf ";\n"
    }
  '
  # Fresh planner statistics after the bulk load.
  echo "analyze public.coffee_health;"
} > "$OUT"

echo "Wrote $OUT ($(tail -n +2 "$CSV" | wc -l | tr -d ' ') rows)"
